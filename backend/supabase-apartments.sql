-- Spaceship v2: one row per apartment (address, building outline, windows with view directions).
-- Run once in Supabase → SQL Editor → New query → Run.
-- Visitors may only ADD rows; nobody can read them with the public key.

create table if not exists public.apartments (
  id          uuid primary key,                 -- generated by the page, also the photo folder name
  created_at  timestamptz not null default now(),
  address     text not null check (char_length(address) <= 300),
  lat         double precision not null,
  lon         double precision not null,
  floor       integer,
  building    jsonb,     -- OSM id, outline ring [[lat,lon],...], levels, height
  windows     jsonb,     -- [{n, label, lat, lon, wall_azimuth_deg, photo_path, capture:{camera_azimuth_deg, camera_elevation_deg, sensor_raw, ...}}]
  client      jsonb
);

alter table public.apartments enable row level security;

revoke all on public.apartments from anon, authenticated;
grant insert on public.apartments to anon;

drop policy if exists "visitors can register an apartment" on public.apartments;
create policy "visitors can register an apartment"
  on public.apartments for insert
  to anon
  with check (true);

-- photos go to the existing private "photos" bucket under <apartment id>/window-<n>.jpg
